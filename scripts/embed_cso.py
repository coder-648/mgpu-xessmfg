#!/usr/bin/env python3
"""Embed a compiled shader (.cso) as a C array for fakerFG.

Usage: embed_cso.py <input.cso> <output.h> <SymbolName>
Produces:  static const unsigned char k<SymbolName>CSO[] = { ... };
"""
import sys

src, dst, symbol = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, "rb").read()

with open(dst, "w", encoding="utf-8") as fh:
    fh.write("// Generated by scripts/embed_cso.py - do not edit.\n")
    fh.write("#pragma once\n\n")
    fh.write(f"static const unsigned char k{symbol}CSO[] = {{\n")
    for off in range(0, len(data), 12):
        chunk = ",".join(f"0x{b:02x}" for b in data[off:off + 12])
        fh.write(f"    {chunk},\n")
    fh.write("};\n")
print(f"[embed] {src} -> {dst} ({len(data)} bytes, k{symbol}CSO)")
